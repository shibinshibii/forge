package filecontent

import (
	"fmt"
	"github.com/shibinshibii/forge/internal/data"
	"strings"
)

const gitignoreContent = `# Go build outputs
*.exe
*.exe~
*.dll
*.so
*.dylib

bin/
dist/

# Testing and coverage
*.test
*.out
*.prof
*.coverprofile
coverage.txt

# Go workspace
go.work
go.work.sum

# Environment files
.env
.env.local
*.local.toml

# Operating system
.DS_Store
Thumbs.db

# Editors
.idea/
*.iml
.vscode/`

const mainTemplate = `package main

import (
	"log"
	"net/http"
	"time"

	"{{MODULE_PATH}}/internal/config"
	"{{MODULE_PATH}}/internal/handlers"
)

func main() {
	cfg := config.Load()

	mux := http.NewServeMux()
	mux.HandleFunc("GET /health", handlers.Health)

	server := &http.Server{
		Addr:              ":" + cfg.Port,
		Handler:           mux,
		ReadHeaderTimeout: 5 * time.Second,
	}

	log.Printf("Server listening on port %s", cfg.Port)

	if err := server.ListenAndServe(); err != nil {
		log.Fatal(err)
	}
}
`

const configContent = `package config

import "os"

type Config struct {
	Port string
}

func Load() Config {
	port := os.Getenv("PORT")
	if port == "" {
		port = "8080"
	}

	return Config{Port: port}
}
`

const handlerContent = `package handlers

import (
	"encoding/json"
	"log"
	"net/http"
)

func Health(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/json")

	if err := json.NewEncoder(w).Encode(
		map[string]string{"status": "ok"},
	); err != nil {
		log.Printf("Error writing health response: %v", err)
	}
}
`

func GenerateFiles(projectName string) []data.File {
	modulePath := fmt.Sprintf("example.com/%s", projectName)
	mainContent := strings.ReplaceAll(
		mainTemplate,
		"{{MODULE_PATH}}",
		modulePath,
	)
	readmeContent := fmt.Sprintf(
		"# %s\n\nGenerated by Forge.\n\nRun with: go run ./cmd/server\n\nHealth endpoint: GET /health\n",
		projectName,
	)

	gomodContent := fmt.Sprintf(
		"module %s\n\ngo 1.23.0\n",
		modulePath,
	)

	return []data.File{
		{
			Name:   "README.md",
			Folder: "",
			Data:   []byte(readmeContent),
		},
		{
			Name:   ".gitignore",
			Folder: "",
			Data:   []byte(gitignoreContent),
		},
		{
			Name:   "go.mod",
			Folder: "",
			Data:   []byte(gomodContent),
		},
		{
			Name:   "main.go",
			Folder: "cmd/server",
			Data:   []byte(mainContent),
		},
		{
			Name:   "config.go",
			Folder: "internal/config",
			Data:   []byte(configContent),
		},
		{
			Name:   "handler.go",
			Folder: "internal/handlers",
			Data:   []byte(handlerContent),
		},
	}
}

package main

import (
	"slices"
	"strings"
	"testing"
)

func TestGenerateFiles(t *testing.T) {
	projectName := "test-project"
	files := generateFiles(projectName)

	wantCount := 6
	if len(files) != wantCount {
		t.Fatalf("got %d files, want %d files", len(files), wantCount)
	}

	expectedFiles := map[string]struct {
		folder       string
		validateData func(t *testing.T, data string)
	}{
		"README.md": {
			folder: "",
			validateData: func(t *testing.T, data string) {
				wantReadme := "# test-project\n\nGenerated by Forge.\n\nRun with: go run ./cmd/server\n\nHealth endpoint: GET /health\n"
				if data != wantReadme {
					t.Errorf("README.md content mismatch:\ngot:\n%s\nwant:\n%s", data, wantReadme)
				}
			},
		},
		".gitignore": {
			folder: "",
			validateData: func(t *testing.T, data string) {
				if data != gitignoreContent {
					t.Errorf(".gitignore content does not match gitignoreContent constant")
				}
				requiredEntries := []string{"*.exe", "bin/", "dist/", "*.test", "*.out", "coverage.txt", "go.work", ".env", ".DS_Store", ".idea/", ".vscode/"}
				for _, entry := range requiredEntries {
					if !strings.Contains(data, entry) {
						t.Errorf(".gitignore missing required entry: %q", entry)
					}
				}
			},
		},
		"go.mod": {
			folder: "",
			validateData: func(t *testing.T, data string) {
				wantGomod := "module example.com/test-project\n\ngo 1.23.0\n"
				if data != wantGomod {
					t.Errorf("go.mod content mismatch:\ngot:\n%s\nwant:\n%s", data, wantGomod)
				}
			},
		},
		"main.go": {
			folder: "cmd/server",
			validateData: func(t *testing.T, data string) {
				if strings.Contains(data, "{{MODULE_PATH}}") {
					t.Errorf("main.go still contains unresolved {{MODULE_PATH}} placeholder")
				}
				expectedImports := []string{
					`"example.com/test-project/internal/config"`,
					`"example.com/test-project/internal/handlers"`,
				}
				for _, imp := range expectedImports {
					if !strings.Contains(data, imp) {
						t.Errorf("main.go missing expected import %s", imp)
					}
				}
				if !strings.Contains(data, "mux.HandleFunc(\"GET /health\", handlers.Health)") {
					t.Errorf("main.go missing health route registration")
				}
				if !strings.Contains(data, "cfg := config.Load()") {
					t.Errorf("main.go missing config loading")
				}
			},
		},
		"config.go": {
			folder: "internal/config",
			validateData: func(t *testing.T, data string) {
				if data != configContent {
					t.Errorf("config.go content does not match configContent constant")
				}
				if !strings.Contains(data, "type Config struct") {
					t.Errorf("config.go missing Config struct")
				}
				if !strings.Contains(data, `os.Getenv("PORT")`) {
					t.Errorf("config.go missing PORT environment lookup")
				}
				if !strings.Contains(data, `"8080"`) {
					t.Errorf("config.go missing default 8080 port")
				}
			},
		},
		"handler.go": {
			folder: "internal/handlers",
			validateData: func(t *testing.T, data string) {
				if data != handlerContent {
					t.Errorf("handler.go content does not match handlerContent constant")
				}
				if !strings.Contains(data, "func Health(w http.ResponseWriter, r *http.Request)") {
					t.Errorf("handler.go missing Health handler function")
				}
				if !strings.Contains(data, `map[string]string{"status": "ok"}`) {
					t.Errorf("handler.go missing status ok json response")
				}
			},
		},
	}

	foundFiles := make(map[string]bool)
	for _, file := range files {
		expected, ok := expectedFiles[file.Name]
		if !ok {
			t.Errorf("unexpected file generated: %q", file.Name)
			continue
		}

		if foundFiles[file.Name] {
			t.Errorf("duplicate file entry found for: %q", file.Name)
		}
		foundFiles[file.Name] = true

		if file.Folder != expected.folder {
			t.Errorf("file %q in folder %q, want %q", file.Name, file.Folder, expected.folder)
		}

		expected.validateData(t, string(file.Data))
	}

	for expectedName := range expectedFiles {
		if !foundFiles[expectedName] {
			t.Errorf("expected file %q was not generated", expectedName)
		}
	}
}

func TestGenerateFiles_FolderConsistency(t *testing.T) {
	files := generateFiles("folder-test")
	for _, file := range files {
		if file.Folder != "" {
			if !slices.Contains(dirs, file.Folder) {
				t.Errorf("file %q placed in folder %q, which is not registered in dirs list (%v)", file.Name, file.Folder, dirs)
			}
		}
	}
}

func TestGenerateFiles_ProjectNames(t *testing.T) {
	tests := []struct {
		name               string
		projectName        string
		expectedModulePath string
	}{
		{
			name:               "standard hyphenated",
			projectName:        "my-service",
			expectedModulePath: "example.com/my-service",
		},
		{
			name:               "alphanumeric with underscore",
			projectName:        "api_v2_core",
			expectedModulePath: "example.com/api_v2_core",
		},
		{
			name:               "single word",
			projectName:        "backend",
			expectedModulePath: "example.com/backend",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			files := generateFiles(tc.projectName)

			var readmeFile, gomodFile, mainFile *File
			for i := range files {
				switch files[i].Name {
				case "README.md":
					readmeFile = &files[i]
				case "go.mod":
					gomodFile = &files[i]
				case "main.go":
					mainFile = &files[i]
				}
			}

			if readmeFile == nil {
				t.Fatalf("README.md not found")
			}
			if !strings.HasPrefix(string(readmeFile.Data), "# "+tc.projectName+"\n") {
				t.Errorf("README.md does not start with expected title for %q", tc.projectName)
			}

			if gomodFile == nil {
				t.Fatalf("go.mod not found")
			}
			expectedGoModLine := "module " + tc.expectedModulePath + "\n"
			if !strings.Contains(string(gomodFile.Data), expectedGoModLine) {
				t.Errorf("go.mod missing expected module line %q; got:\n%s", expectedGoModLine, string(gomodFile.Data))
			}

			if mainFile == nil {
				t.Fatalf("main.go not found")
			}
			mainContent := string(mainFile.Data)
			if strings.Contains(mainContent, "{{MODULE_PATH}}") {
				t.Errorf("main.go still contains unresolved {{MODULE_PATH}} placeholder")
			}
			expectedConfigImport := `"` + tc.expectedModulePath + `/internal/config"`
			expectedHandlerImport := `"` + tc.expectedModulePath + `/internal/handlers"`
			if !strings.Contains(mainContent, expectedConfigImport) {
				t.Errorf("main.go missing config import %s", expectedConfigImport)
			}
			if !strings.Contains(mainContent, expectedHandlerImport) {
				t.Errorf("main.go missing handler import %s", expectedHandlerImport)
			}
		})
	}
}
